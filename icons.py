# (키워드, 이모지) 목록. 긴 키워드부터 비교한다.
_KEYWORDS: list[tuple[str, str]] = sorted(
    ((kw.lower(), emoji) for emoji, kws in ICON_KEYWORDS for kw in kws),
    key=lambda pair: len(pair[0]),
    reverse=True,
)

# 영어 키워드 → 단어 경계 정규식 (앞뒤에 영문자가 없어야 함, 복수형 s/es 허용)
_ASCII_PATTERNS: dict[str, re.Pattern] = {
    kw: re.compile(rf"(?<![a-z]){re.escape(kw)}(?:e?s)?(?![a-z])")
    for kw, _ in _KEYWORDS
    if kw.isascii()
}


def get_icon(name: str) -> str:
    """아이템 이름에 맞는 이모지를 반환한다."""
    text = (name or "").strip().lower()
    if not text:
        return DEFAULT_ICON
    tokens = set(text.split())
    for keyword, emoji in _KEYWORDS:
        if keyword in _ASCII_PATTERNS:
            if _ASCII_PATTERNS[keyword].search(text):
                return emoji
        elif len(keyword) == 1:
            if keyword in tokens:
                return emoji
        elif keyword in text:
            return emoji
    return DEFAULT_ICON
